def main():
    out = Path(__file__).with_name("relation_benchmark.jsonl")
    with out.open("w") as f:
        for k, (text, mics, mets, rels, neg, tags) in enumerate(ITEMS, 1):
            for m in mics:
                assert m in text, (k, m)
            for x in mets:
                assert x in text, (k, x)
            for m, x, *_ in rels + [(a, b) for a, b in neg]:
                assert m in mics and x in mets, (k, m, x)
            f.write(json.dumps({
                "id": f"s{k:03d}", "text": text, "microbes": mics, "metabolites": mets,
                "relations": [{"microbe": m, "metabolite": x, "types": t} for m, x, t in rels],
                "negated": [{"microbe": m, "metabolite": x} for m, x in neg],
                "tags": tags,
            }) + "\n")
    print(f"wrote {len(ITEMS)} items to {out}")


if __name__ == "__main__":
    main()
